def P(H, f, d):
    return H * f / (0.2025 * d)

def vfov_half(f):
    return math.degrees(math.atan(10.125 / f))

def side(cam, look, pt):
    """>0: точка справа от линии взгляда камеры, <0: слева (вид сверху)."""
    dx, dy = look[0] - cam[0], look[1] - cam[1]
    rx, ry = dy, -dx
    return (pt[0] - cam[0]) * rx + (pt[1] - cam[1]) * ry

