def timeline():
    """Возвращает список (id, file, in, out, t0) — где каждый клип стоит на монтаже."""
    out, t = [], 0.0
    for cid, f, a, b, mv, note in CLIPS:
        if DISSOLVE and cid == DISSOLVE[1]: t -= DISSOLVE[2]
        out.append((cid, f, a, b, t)); t += (b - a)
    return out, t

def at(cid, local):
    """Время на монтаже для момента local внутри дубля клипа cid (None, если вырезано)."""
    for c, f, a, b, t0 in timeline()[0]:
        if c == cid and a - 1e-6 <= local <= b + 1e-6: return t0 + (local - a)
    return None

def start(cid): return next(t0 for c, f, a, b, t0 in timeline()[0] if c == cid)
def end(cid):   return next(t0 + (b - a) for c, f, a, b, t0 in timeline()[0] if c == cid)

if __name__ == "__main__":
    tl, total = timeline()
